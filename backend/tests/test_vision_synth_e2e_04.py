class TestSHA256Verification:
    """SHA256-01..10 — verify every fixture file against MANIFEST.json checksums."""

    def _sha256(self, path: Path) -> str:
        h = hashlib.sha256()
        with open(path, "rb") as f:
            for chunk in iter(lambda: f.read(65536), b""):
                h.update(chunk)
        return h.hexdigest()

    @pytest.mark.parametrize("entry", _ALL_VIDEOS,
                             ids=[v["scenario"] for v in _ALL_VIDEOS])
    def test_sha256_matches_manifest(self, entry):
        path = _VID_DIR / entry["filename"]
        assert path.exists(), f"Fixture file not found: {path}"
        actual = self._sha256(path)
        expected = entry["sha256"]
        assert actual == expected, (
            f"{entry['scenario']}: SHA256 mismatch\n"
            f"  actual:   {actual}\n"
            f"  expected: {expected}"
        )

    def test_all_10_files_present(self):
        """All 10 fixture files referenced in MANIFEST.json must exist."""
        missing = []
        for v in _ALL_VIDEOS:
            p = _VID_DIR / v["filename"]
            if not p.exists():
                missing.append(v["filename"])
        assert not missing, f"Missing fixture files: {missing}"

    def test_manifest_version_and_total(self):
        """Manifest must declare version=1.0.0 and total_videos=10."""
        assert _MANIFEST["version"] == "1.0.0"
        assert _MANIFEST["total_videos"] == 10
        assert len(_ALL_VIDEOS) == 10


