class TestGenerateDeliverables:
    """Generate VIDEO_10_FILE_ACCEPTANCE.csv and TEMPORAL_EVENT_ACCEPTANCE.csv."""

    def test_generate_video_10_file_acceptance_csv(self):
        """Generate VIDEO_10_FILE_ACCEPTANCE.csv with actual file inspection results."""
        import cv2

        rows = []
        for v in _ALL_VIDEOS:
            path = _VID_DIR / v["filename"]
            if not path.exists():
                rows.append({
                    "scenario": v["scenario"], "filename": v["filename"],
                    "status": "MISSING", "sha256_ok": "FAIL",
                    "codec_ok": "FAIL", "resolution": "N/A", "fps": "N/A",
                    "duration_s": "N/A", "frame_count": "N/A", "accept": "FAIL",
                })
                continue

            # SHA256
            h = hashlib.sha256()
            with open(path, "rb") as f:
                for chunk in iter(lambda: f.read(65536), b""):
                    h.update(chunk)
            sha_ok = "PASS" if h.hexdigest() == v["sha256"] else "FAIL"

            if v["status"] == "INTENTIONAL_ERROR":
                rows.append({
                    "scenario": v["scenario"], "filename": v["filename"],
                    "status": "INTENTIONAL_ERROR", "sha256_ok": sha_ok,
                    "codec_ok": "N/A", "resolution": "N/A", "fps": "N/A",
                    "duration_s": "N/A", "frame_count": "N/A", "accept": "PASS" if sha_ok == "PASS" else "FAIL",
                })
                continue

            # cv2 inspection
            cap = cv2.VideoCapture(str(path))
            w = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
            h_px = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
            fps = cap.get(cv2.CAP_PROP_FPS)
            n_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
            opened = cap.isOpened()
            cap.release()

            # Full decode count
            cap2 = cv2.VideoCapture(str(path))
            actual_frames = 0
            while True:
                ok, _ = cap2.read()
                if not ok:
                    break
                actual_frames += 1
            cap2.release()

            expected_frames = int(v["fps"] * v["duration_s"])
            duration_actual = n_frames / fps if fps > 0 else 0

            w_ok   = w == v["width"] and h_px == v["height"]
            fps_ok = abs(fps - v["fps"]) < 1.0
            dur_ok = abs(duration_actual - v["duration_s"]) <= (1.0 / v["fps"] + 0.01)
            cnt_ok = actual_frames == expected_frames

            accept = "PASS" if (sha_ok == "PASS" and opened and w_ok and fps_ok and dur_ok and cnt_ok) else "FAIL"
            rows.append({
                "scenario": v["scenario"],
                "filename": v["filename"],
                "status": v["status"],
                "sha256_ok": sha_ok,
                "codec_ok": "PASS" if opened else "FAIL",
                "resolution": f"{w}x{h_px}",
                "fps": f"{fps:.1f}",
                "duration_s": f"{duration_actual:.3f}",
                "frame_count": str(actual_frames),
                "accept": accept,
            })

        csv_path = _DOCS_DIR / "VIDEO_10_FILE_ACCEPTANCE.csv"
        with open(csv_path, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=[
                "scenario", "filename", "status", "sha256_ok", "codec_ok",
                "resolution", "fps", "duration_s", "frame_count", "accept"
            ])
            writer.writeheader()
            writer.writerows(rows)

        # Assert all 10 rows present and 9 valid ones are PASS
        assert len(rows) == 10, f"Expected 10 rows, got {len(rows)}"
        pass_count = sum(1 for r in rows if r["accept"] == "PASS")
        assert pass_count == 10, (
            f"Expected 10 PASS rows, got {pass_count}; failures: "
            f"{[r['scenario'] for r in rows if r['accept'] != 'PASS']}"
        )

