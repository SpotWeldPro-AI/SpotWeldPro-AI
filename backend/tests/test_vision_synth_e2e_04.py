class TestCodecInspection:
    """CODEC-01..09 — verify codec, resolution, FPS and duration against manifest using cv2."""

    @pytest.fixture(autouse=True)
    def _require_cv2(self):
        if _cv2_skip():
            pytest.skip("opencv not installed")

    @pytest.mark.parametrize("entry", _VALID_VIDEOS,
                             ids=[v["scenario"] for v in _VALID_VIDEOS])
    def test_resolution_matches_manifest(self, entry):
        import cv2
        path = str(_VID_DIR / entry["filename"])
        cap = cv2.VideoCapture(path)
        try:
            w = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
            h = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
        finally:
            cap.release()
        assert w == entry["width"],  f"{entry['scenario']}: width={w} expected={entry['width']}"
        assert h == entry["height"], f"{entry['scenario']}: height={h} expected={entry['height']}"

    @pytest.mark.parametrize("entry", _VALID_VIDEOS,
                             ids=[v["scenario"] for v in _VALID_VIDEOS])
    def test_fps_matches_manifest(self, entry):
        import cv2
        path = str(_VID_DIR / entry["filename"])
        cap = cv2.VideoCapture(path)
        try:
            fps = cap.get(cv2.CAP_PROP_FPS)
        finally:
            cap.release()
        assert abs(fps - entry["fps"]) < 1.0, (
            f"{entry['scenario']}: cv2 FPS={fps:.2f} expected={entry['fps']}"
        )

    @pytest.mark.parametrize("entry", _VALID_VIDEOS,
                             ids=[v["scenario"] for v in _VALID_VIDEOS])
    def test_duration_matches_manifest(self, entry):
        import cv2
        path = str(_VID_DIR / entry["filename"])
        cap = cv2.VideoCapture(path)
        try:
            fps   = cap.get(cv2.CAP_PROP_FPS)
            count = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
        finally:
            cap.release()
        if fps > 0:
            duration = count / fps
            # Allow ±1 frame tolerance
            tol = 1.0 / fps + 0.01
            assert abs(duration - entry["duration_s"]) <= tol, (
                f"{entry['scenario']}: duration={duration:.3f}s expected={entry['duration_s']}s"
            )

    @pytest.mark.parametrize("entry", _VALID_VIDEOS,
                             ids=[v["scenario"] for v in _VALID_VIDEOS])
    def test_codec_is_readable(self, entry):
        """cv2 must be able to open and return a non-zero fourcc for each valid MP4."""
        import cv2
        path = str(_VID_DIR / entry["filename"])
        cap = cv2.VideoCapture(path)
        try:
            opened = cap.isOpened()
        finally:
            cap.release()
        assert opened, f"{entry['scenario']}: cv2 could not open {path}"


